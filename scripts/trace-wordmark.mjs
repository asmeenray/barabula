// One-off dev script: traces the "Barabula." wordmark from Abril Fatface into
// a single SVG path (D-04 allows an SVG wordmark; UI-SPEC "Font").
//
//   node scripts/trace-wordmark.mjs
//
// Downloads AbrilFatface-Regular.ttf (SIL OFL 1.1) from google/fonts into the
// OS temp dir (never into the repo), lays the text out with Next's bundled
// fontkit, flips the y axis, applies advances and kerning, and writes
// src/components/brand/wordmark-path.ts. The font file itself is not shipped.

import { createRequire } from 'node:module'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const FONT_URL = 'https://github.com/google/fonts/raw/main/ofl/abrilfatface/AbrilFatface-Regular.ttf'
const FONT_FILE = path.join(tmpdir(), 'barabula-AbrilFatface-Regular.ttf')
const TEXT = 'Barabula.'
const OUT = path.join(root, 'src/components/brand/wordmark-path.ts')

async function fontBuffer() {
  if (existsSync(FONT_FILE)) return readFileSync(FONT_FILE)
  const res = await fetch(FONT_URL, { redirect: 'follow' })
  if (!res.ok) throw new Error(`Font download failed: ${res.status} ${res.statusText}`)
  const buf = Buffer.from(await res.arrayBuffer())
  writeFileSync(FONT_FILE, buf)
  return buf
}

// Next's compiled fontkit: the default export is fontkit.create(buffer).
const fontkitModule = require(path.join(root, 'node_modules/next/dist/compiled/@next/font/dist/fontkit')).default
const createFont = fontkitModule.default || fontkitModule

const round = (n) => Math.round(n * 10) / 10

const font = createFont(await fontBuffer())
const run = font.layout(TEXT)

// Font units, y up. Place each glyph at its pen position, flip y with the
// ascent as the baseline offset, then crop the viewBox to the ink bounds.
let x = 0
const parts = []
let minX = Infinity
let minY = Infinity
let maxX = -Infinity
let maxY = -Infinity
const tx = (gx, ox) => gx + ox
const ty = (gy, oy) => font.ascent - (gy + oy)

run.glyphs.forEach((glyph, i) => {
  const pos = run.positions[i]
  const ox = x + pos.xOffset
  const oy = pos.yOffset
  for (const cmd of glyph.path.commands) {
    const a = cmd.args
    const pts = []
    for (let k = 0; k < a.length; k += 2) pts.push([tx(a[k], ox), ty(a[k + 1], oy)])
    for (const [px, py] of pts) {
      minX = Math.min(minX, px)
      maxX = Math.max(maxX, px)
      minY = Math.min(minY, py)
      maxY = Math.max(maxY, py)
    }
    const flat = pts.flat().map(round).join(' ')
    switch (cmd.command) {
      case 'moveTo':
        parts.push(`M${flat}`)
        break
      case 'lineTo':
        parts.push(`L${flat}`)
        break
      case 'quadraticCurveTo':
        parts.push(`Q${flat}`)
        break
      case 'bezierCurveTo':
        parts.push(`C${flat}`)
        break
      case 'closePath':
        parts.push('Z')
        break
      default:
        throw new Error(`Unknown path command ${cmd.command}`)
    }
  }
  x += pos.xAdvance
})

if (parts.length === 0) throw new Error('fontkit produced no outlines')

const vbX = Math.floor(minX)
const vbY = Math.floor(minY)
const vbW = Math.ceil(maxX) - vbX
const vbH = Math.ceil(maxY) - vbY

const out = `// Generated by scripts/trace-wordmark.mjs from Abril Fatface (SIL Open Font
// License 1.1, google/fonts). Do not edit by hand; re-run the script.
// "${TEXT}" as one path, in font units (${font.unitsPerEm}/em), cropped to the ink.

export const WORDMARK_VIEWBOX = '${vbX} ${vbY} ${vbW} ${vbH}'

export const WORDMARK_PATH =
  '${parts.join('')}'
`

writeFileSync(OUT, out)
console.log(`Wrote ${path.relative(root, OUT)}: ${parts.length} commands, viewBox ${vbX} ${vbY} ${vbW} ${vbH}`)
